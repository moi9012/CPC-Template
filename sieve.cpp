vector<int> primes;      // 存储筛选出的素数
vector<bool> is_comp;    // 标记数组，is_comp[i] = true 表示 i 是合数

/*
 * ================== 线性筛 (欧拉筛) ==================
 * 【核心思想】
 * 利用“每个合数只会被它的最小质因子筛掉”的性质，确保每个合数仅被标记一次，
 * 从而将时间复杂度从埃氏筛的 O(n log log n) 严格优化至 O(n)。
 * 
 * 【关键逻辑】
 * 1. 外层遍历 i，若 i 未被标记，则 i 为素数，加入 primes 数组。
 * 2. 内层用 primes 中的素数去筛 i * p。
 * 3. 核心剪枝：当 i % p == 0 时，说明 p 已经是 i 的最小质因子。
 *    此时对于 primes 中 p 后面的更大素数 p'，合数 i * p' 的最小质因子应为 p，
 *    它会在未来遍历到 i' = i / p * p' 时被 p 筛掉。因此必须 break，防止重复标记。
 * 
 * 【时间复杂度】
 * 严格 O(n)，每个合数仅被访问一次。
 * 
 * 【常见应用】
 * 1. 快速预处理 $10^7$ 级别的素数表。
 * 2. 结合线性筛求积性函数（如欧拉函数 φ、莫比乌斯函数 μ、约数和 σ 等）。
 * =====================================================
 */
void get_primes(int n) {
    is_comp.assign(n + 1, false);
    for (int i = 2; i <= n; ++i) {
        if (!is_comp[i]) primes.push_back(i); // i 是素数，加入素数表
        
        // 用当前已知的素数去筛 i 的倍数
        for (int p : primes) {
            if ((ll)i * p > n) break;         // 防止溢出，且超出范围无需继续
            is_comp[i * p] = true;            // 标记合数
            
            // 核心剪枝：保证每个合数只被其最小质因子筛掉
            // 若 i 能被 p 整除，说明 p 是 i 的最小质因子。
            // 此时若继续用更大的素数 p' 去筛 i * p'，
            // 则 i * p' 的最小质因子仍是 p，但它会被 p' 错误地筛掉，导致重复标记。
            // 因此必须在此处终止内层循环。
            if (i % p == 0) break; 
        }
    }
}