struct STTable {
    // f[j][i] 表示从下标 i 开始，长度为 2^j 的区间内的最值
    vector<vector<int>> f;
    // log[i] 预处理 floor(log2(i))，避免查询时调用耗时的 log2 函数
    vector<int> log;

    /*
     * ================== 预处理（build） ==================
     * 【核心思想】
     * 利用动态规划和二进制倍增思想：
     * 任意长度为 len 的区间，都可以拆分为两个长度为 2^k (2^k <= len) 的区间。
     * 递推方程：f[j][i] = max(f[j-1][i], f[j-1][i + 2^(j-1)])
     * 即：长度为 2^j 的区间最值 = max(左半部分 2^(j-1) 的最值, 右半部分 2^(j-1) 的最值)
     * 
     * 【时间复杂度】O(n log n)
     * 【空间复杂度】O(n log n)
     * =====================================================
     */
    void build(vector<int> &a) {
        int n = a.size();
        
        // 1. 预处理对数，log[i] = floor(log2(i))
        // 递推：log[i] = log[i >> 1] + 1
        log.assign(n + 1, 0);
        for (int i = 2; i <= n; ++i) log[i] = log[i >> 1] + 1;
        
        // 2. 初始化 ST 表，第 0 层即为原数组
        f.assign(log[n] + 1, vector<int>(n));
        f[0] = a;
        
        // 3. 倍增递推填表
        for (int j = 1; (1 << j) <= n; ++j) {
            // 注意边界：i + (1 << j) <= n，确保区间不越界
            for (int i = 0; i + (1 << j) <= n; ++i) {
                f[j][i] = max(f[j - 1][i], f[j - 1][i + (1 << (j - 1))]);
            }
        }
    }

    /*
     * ================== 区间查询（query） ==================
     * 【核心思想：区间重叠技巧】
     * 查询 [l, r] 的最值时，取 k = floor(log2(r - l + 1))。
     * 用两个长度为 2^k 的区间去覆盖 [l, r]：
     * 区间1：[l, l + 2^k - 1]
     * 区间2：[r - 2^k + 1, r]
     * 由于 2^(k+1) > (r - l + 1)，这两个区间必然能完全覆盖 [l, r]，且中间可能有重叠。
     * 因为 max/min 操作满足**幂等性**（即 max(a, a) = a），重叠部分不影响结果。
     * 
     * 【时间复杂度】O(1)
     * ======================================================
     */
    int query(int l, int r) {
        int k = log[r - l + 1]; // 找到最大的 k，使得 2^k <= 区间长度
        // 取两个重叠区间的最大值
        return max(f[k][l], f[k][r - (1 << k) + 1]);
    }
};