/*
 * ================== 数位 DP (Digit DP) 模板 ==================
 * 【核心思想】
 * 将数字视为字符串，从高位到低位逐位确定。
 * 利用 DFS + 记忆化搜索，将“枚举所有数字”转化为“枚举每一位的可能取值”。
 * 
 * 【区间处理套路】
 * 题目通常要求 [L, R] 区间的答案，利用前缀和思想转化为：
 * Ans = solve(R) - solve(L - 1)
 * 其中 solve(N) 表示 [0, N] 中满足条件的数字个数。
 * 
 * 【关键状态】
 * 1. pos：当前处理到的位置（从 0 开始）。
 * 2. limit：是否受上界限制（最核心的标记，见下方注释）。
 * 3. state：自定义状态（如前一位是否为 4、数字和、前导零等）。
 * ===========================================================
 */

// 记忆化数组：memo[pos][limit]，实际使用时 limit 维度通常省略或单独处理
// 注意：只有 !limit 的状态才具有通用性，才能被缓存
ll memo[20][2]; 
string s; // 将上界 N 转为字符串，方便逐位处理

/*
 * 【DFS 核心逻辑】
 * pos: 当前枚举到第几位
 * limit: 当前位是否受上界 N 的限制
 */
ll dfs(int pos, bool limit) {
    // 边界条件：所有位处理完毕，说明成功构造了一个合法数字，返回 1
    if (pos == s.size()) return 1;
    
    // 记忆化：如果当前不受限制，且该状态已经计算过，直接返回缓存结果
    // 为什么只有 !limit 才能记忆化？
    // 因为 limit=true 的状态是“临时”的（受限于具体的 N），而 limit=false 的状态
    // 是“通用”的（后续位可以随便填 0~9），不同数字在不受限时会走到相同的子问题。
    if (!limit && memo[pos][1] != -1) return memo[pos][1];
    
    // 确定当前位的上限：
    // 如果受限制（limit=true），当前位最大只能填 s[pos]（N 在这一位的值）
    // 如果不受限（limit=false），当前位可以随便填 0~9
    int up = limit ? s[pos] - '0' : 9;
    
    ll res = 0;
    for (int i = 0; i <= up; ++i) {
        if (i == 4) continue; // 题目条件：不含数字 4，遇到 4 直接跳过
        
        // 递归处理下一位
        // limit 的转移逻辑：
        // 只有当“当前受限制” 且 “当前位填了上限值” 时，下一位才继续受限制
        // 只要当前位填得比上限小，后续所有位都彻底解放（limit=false）
        res += dfs(pos + 1, limit && (i == up));
    }
    
    // 缓存结果：同样，只有不受限时才存入 memo
    if (!limit) memo[pos][1] = res;
    return res;
}

/*
 * 【solve 函数】
 * 将数字 N 转为字符串，初始化 memo，从第 0 位开始 DFS
 * 注意：初始时 limit 必须为 true，因为最高位受 N 的限制
 */
ll solve(ll N) {
    s = to_string(N);
    memset(memo, -1, sizeof(memo));
    return dfs(0, true);
}