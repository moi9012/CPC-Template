struct Trie {
    // nxt[p][i] 表示节点 p 通过字符 i（'a'~'z'）转移到的子节点编号
    // 若为 0 表示不存在该子节点
    vector<array<int, 26>> nxt;
    
    // cnt[p] 表示以节点 p 结尾的字符串出现次数
    // 若只关心"是否存在"，可用 bool 替代 int
    vector<int> cnt;
    
    // tot 记录当前已分配的节点总数（0 为根节点）
    int tot;
    
    /*
     * ================== 初始化 ==================
     * 创建根节点（编号 0），所有转移边初始化为 0（无子节点）
     * ============================================
     */
    Trie() {
        nxt.push_back(array<int, 26>());
        nxt[0].fill(0);
        cnt.push_back(0);
        tot = 0;
    }
    
    /*
     * ================== 插入字符串 ==================
     * 【核心思想】
     * 从根节点出发，逐字符沿转移边向下走：
     * 1. 若当前字符对应的子节点不存在，则新建节点。
     * 2. 移动到子节点，继续处理下一个字符。
     * 3. 字符串末尾节点的 cnt 加 1，表示该字符串出现次数 +1。
     * 
     * 【时间复杂度】O(|s|)，|s| 为字符串长度
     * ==============================================
     */
    void insert(const string &s) {
        int p = 0; // 从根节点出发
        for (char c : s) {
            int i = c - 'a'; // 字符映射到 0~25
            if (!nxt[p][i]) { // 子节点不存在，新建
                nxt.push_back(array<int, 26>());
                nxt.back().fill(0);
                cnt.push_back(0);
                nxt[p][i] = ++tot; // 分配新节点编号
            }
            p = nxt[p][i]; // 移动到子节点
        }
        cnt[p]++; // 标记字符串结尾，计数 +1
    }
    
    /*
     * ================== 查询字符串 ==================
     * 【核心思想】
     * 从根节点出发，逐字符沿转移边向下走：
     * 1. 若某字符对应的子节点不存在，说明字符串不在 Trie 中，返回 0。
     * 2. 若成功走到末尾，返回该节点的 cnt（字符串出现次数）。
     * 
     * 【时间复杂度】O(|s|)
     * ==============================================
     */
    int query(const string &s) {
        int p = 0;
        for (char c : s) {
            int i = c - 'a';
            if (!nxt[p][i]) return 0; // 路径断裂，字符串不存在
            p = nxt[p][i];
        }
        return cnt[p]; // 返回字符串出现次数
    }
};